# ============================================================
# GENERATE PROJECT IDEAS
# ============================================================

def generate_project_ideas(
    title: str = "",
    abstract: str = "",
    gaps: Any = "",
    papers: Any = None,
    research_gaps_text: Any = None,
) -> Dict[str, Any]:
    """
    Generate project ideas exclusively through Ollama.

    Multi-paper workflow:

        papers
            +
        research_gaps_text
            ↓
        Ollama
            ↓
        five project ideas

    No project idea is generated by Python.
    """

    use_multi_paper_flow = (
        papers is not None
    )

    # ========================================================
    # MULTI-PAPER WORKFLOW
    # ========================================================

    if use_multi_paper_flow:

        normalized_papers = normalize_papers(
            papers
        )

        normalized_papers = normalized_papers[
            :MAX_PAPERS
        ]

        if not normalized_papers:

            raise ValueError(
                "No usable research papers were provided for project ideation."
            )

        gap_source = (
            research_gaps_text
            if research_gaps_text is not None
            else gaps
        )

        gap_text = format_research_gaps(
            gap_source
        )

        if not gap_text:

            raise ValueError(
                "No research gaps were provided for project ideation."
            )

        source_papers_text = format_source_papers(
            normalized_papers
        )

        prompt = build_project_ideation_prompt(
            source_papers_text,
            gap_text
        )

    # ========================================================
    # LEGACY SINGLE-PAPER WORKFLOW
    # ========================================================

    else:

        title = str(
            title or ""
        ).strip()

        abstract = str(
            abstract or ""
        ).strip()

        if not title:

            raise ValueError(
                "A paper title is required."
            )

        if not abstract:

            raise ValueError(
                "A paper abstract is required."
            )

        gap_text = format_research_gaps(
            gaps
        )

        if not gap_text:

            raise ValueError(
                "Research-gap information is required."
            )

        source_papers_text = f"""
PAPER 1

Title:
{title}

Abstract:
{abstract}
""".strip()

        prompt = build_project_ideation_prompt(
            source_papers_text,
            gap_text
        )

    # ========================================================
    # OLLAMA REQUEST
    # ========================================================

    payload = {
        "model":
            OLLAMA_MODEL,

        "prompt":
            prompt,

        "stream":
            False,

        "format":
            "json",
    }

    try:

        response = requests.post(
            OLLAMA_URL,
            json=payload,
            timeout=180
        )

    except requests.RequestException as exc:

        raise RuntimeError(
            f"Project ideation service is unavailable: {exc}"
        ) from exc

    # ========================================================
    # HTTP ERROR
    # ========================================================

    if not response.ok:

        try:

            error_data = response.json()

        except Exception:

            error_data = {}

        error_message = None

        if isinstance(
            error_data,
            dict
        ):

            error_message = (
                error_data.get(
                    "error"
                )
            )

        raise RuntimeError(
            error_message
            or (
                "Project ideation service returned "
                f"HTTP {response.status_code}."
            )
        )

    # ========================================================
    # READ OLLAMA RESPONSE
    # ========================================================

    try:

        response_data = response.json()

    except ValueError as exc:

        raise ValueError(
            "The project ideation service returned an invalid HTTP response."
        ) from exc

    generated_text = ""

    if isinstance(
        response_data,
        dict
    ):

        generated_text = (
            response_data.get(
                "response"
            )
            or response_data.get(
                "content"
            )
            or ""
        )

    elif isinstance(
        response_data,
        str
    ):

        generated_text = response_data

    if not generated_text:

        raise ValueError(
            "The project ideation service returned no generated content."
        )

    # ========================================================
    # PARSE OLLAMA JSON
    # ========================================================

    parsed = clean_json_response(
        generated_text
    )

    # ========================================================
    # EXTRACT IDEAS
    # ========================================================

    raw_ideas = extract_ideas(
        parsed
    )

    if not raw_ideas:

        raise ValueError(
            "The project ideation service returned no project ideas."
        )

    # ========================================================
    # NORMALIZE + VALIDATE
    # ========================================================

    normalized_ideas = []

    for index, raw_idea in enumerate(
        raw_ideas,
        start=1
    ):

        idea = normalize_idea(
            raw_idea,
            index
        )

        if not is_valid_idea(
            idea
        ):

            continue

        normalized_ideas.append(
            idea
        )

    # ========================================================
    # REQUIRE FIVE LLM-GENERATED IDEAS
    # ========================================================

    if len(
        normalized_ideas
    ) < MAX_IDEAS:

        raise ValueError(
            "The project ideation service returned "
            f"{len(normalized_ideas)} usable ideas. "
            "Exactly 5 LLM-generated project ideas are required."
        )

    normalized_ideas = normalized_ideas[
        :MAX_IDEAS
    ]

    # ========================================================
    # FINAL RESPONSE
    # ========================================================

    return {
        "analysis_status":
            "ideas_generated",

        "idea_count":
            len(normalized_ideas),

        "paper_count":
            (
                len(normalized_papers)
                if use_multi_paper_flow
                else 1
            ),

        # Each item is a completely separate project idea.
        "ideas":
            normalized_ideas,
    }


