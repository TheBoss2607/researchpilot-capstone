"""
RESEARCHPILOT - Project Ideation

Pipeline:

    Selected research papers
            +
    Research gaps generated by the Research Gap stage
            ↓
    Local Ollama model
            ↓
    Five project ideas
            ↓
    Each idea contains its own:
        - title
        - problem statement
        - research gap
        - proposed approach
        - technologies
        - relevance
        - difficulty
        - evaluation
        - expected outcome

IMPORTANT:

    - ALL project-idea content is generated by the local Ollama model.
    - This module does NOT generate research gaps.
    - This module does NOT use GWO.
    - This module does NOT use Hill Climbing.
    - This module does NOT use sklearn.
    - This module does NOT use numpy.
    - This module does NOT use pandas.
    - Python only prepares the input, calls Ollama, parses JSON,
      and validates the returned structure.
"""


import json
import re
import requests

from typing import Any, Dict, List


# ============================================================
# CONFIGURATION
# ============================================================

OLLAMA_URL = "http://localhost:11434/api/generate"

OLLAMA_MODEL = "llama3.2:latest"

MAX_PAPERS = 5

MAX_IDEAS = 5


# ============================================================
# JSON CLEANING
# ============================================================

def clean_json_response(
    text: str
) -> Any:
    """
    Parse JSON returned by Ollama.

    Handles:

        - normal JSON
        - markdown code fences
        - JSON objects embedded in text
        - JSON arrays embedded in text
    """

    if not text:

        raise ValueError(
            "The project ideation service returned an empty response."
        )

    cleaned = str(
        text
    ).strip()

    # --------------------------------------------------------
    # Remove markdown code fences.
    # --------------------------------------------------------

    if cleaned.startswith("```"):

        cleaned = re.sub(
            r"^```(?:json)?\s*",
            "",
            cleaned,
            flags=re.IGNORECASE
        )

        cleaned = re.sub(
            r"\s*```$",
            "",
            cleaned
        )

        cleaned = cleaned.strip()

    # --------------------------------------------------------
    # Direct JSON parsing.
    # --------------------------------------------------------

    try:

        return json.loads(
            cleaned
        )

    except json.JSONDecodeError:

        pass

    # --------------------------------------------------------
    # Extract JSON object.
    # --------------------------------------------------------

    object_start = cleaned.find(
        "{"
    )

    object_end = cleaned.rfind(
        "}"
    )

    if (
        object_start != -1
        and object_end != -1
        and object_end > object_start
    ):

        object_text = cleaned[
            object_start:
            object_end + 1
        ]

        try:

            return json.loads(
                object_text
            )

        except json.JSONDecodeError:

            pass

    # --------------------------------------------------------
    # Extract JSON array.
    # --------------------------------------------------------

    array_start = cleaned.find(
        "["
    )

    array_end = cleaned.rfind(
        "]"
    )

    if (
        array_start != -1
        and array_end != -1
        and array_end > array_start
    ):

        array_text = cleaned[
            array_start:
            array_end + 1
        ]

        try:

            return json.loads(
                array_text
            )

        except json.JSONDecodeError:

            pass

    raise ValueError(
        "The project ideation service did not return valid JSON."
    )


# ============================================================
# PAPER NORMALIZATION
# ============================================================

def normalize_papers(
    papers: Any
) -> List[Dict[str, Any]]:
    """
    Normalize paper objects received from Flask/frontend.

    A paper is usable when it contains:

        - a title
        - an abstract/summary
    """

    if not isinstance(
        papers,
        list
    ):

        return []

    normalized = []

    for index, paper in enumerate(
        papers
    ):

        if not isinstance(
            paper,
            dict
        ):

            continue

        title = (
            paper.get("title")
            or paper.get("name")
            or ""
        )

        abstract = (
            paper.get("abstract")
            or paper.get("summary")
            or paper.get("description")
            or ""
        )

        title = str(
            title
        ).strip()

        abstract = str(
            abstract
        ).strip()

        if not title:

            continue

        if not abstract:

            continue

        normalized.append(
            {
                "paper_number":
                    index + 1,

                "id":
                    (
                        paper.get("id")
                        or paper.get("work_id")
                    ),

                "title":
                    title,

                "abstract":
                    abstract,
            }
        )

    return normalized


# ============================================================
# FORMAT SOURCE PAPERS
# ============================================================

def format_source_papers(
    papers: List[Dict[str, Any]]
) -> str:
    """
    Convert the selected papers into prompt text.

    The actual paper abstracts are passed directly to Ollama.
    """

    sections = []

    for index, paper in enumerate(
        papers,
        start=1
    ):

        sections.append(
            f"""
PAPER {index}

Title:
{paper.get("title", "")}

Abstract:
{paper.get("abstract", "")}
""".strip()
        )

    return "\n\n".join(
        sections
    )


# ============================================================
# FORMAT RESEARCH GAPS
# ============================================================

def format_research_gaps(
    research_gaps: Any = ""
) -> str:
    """
    Convert the research gaps generated by the previous
    stage into prompt text.

    IMPORTANT:

        This function does NOT create research gaps.

        It only formats whatever was already generated
        by the Research Gap Identification stage.
    """

    if research_gaps is None:

        return ""

    # --------------------------------------------------------
    # String
    # --------------------------------------------------------

    if isinstance(
        research_gaps,
        str
    ):

        return research_gaps.strip()

    # --------------------------------------------------------
    # Dictionary wrapper
    # --------------------------------------------------------

    if isinstance(
        research_gaps,
        dict
    ):

        if "research_gaps" in research_gaps:

            return format_research_gaps(
                research_gaps[
                    "research_gaps"
                ]
            )

        if "gaps" in research_gaps:

            return format_research_gaps(
                research_gaps[
                    "gaps"
                ]
            )

        # A single LLM-generated gap object.
        parts = []

        gap_id = (
            research_gaps.get(
                "gap_id"
            )
            or research_gaps.get(
                "id"
            )
        )

        description = (
            research_gaps.get(
                "description"
            )
            or research_gaps.get(
                "research_gap"
            )
            or ""
        )

        evidence = (
            research_gaps.get(
                "evidence"
            )
            or ""
        )

        opportunity = (
            research_gaps.get(
                "research_opportunity"
            )
            or ""
        )

        category = (
            research_gaps.get(
                "category"
            )
            or ""
        )

        if gap_id:

            parts.append(
                str(gap_id)
            )

        if description:

            parts.append(
                f"Description: {description}"
            )

        if evidence:

            parts.append(
                f"Evidence: {evidence}"
            )

        if opportunity:

            parts.append(
                f"Research Opportunity: {opportunity}"
            )

        if category:

            parts.append(
                f"Category: {category}"
            )

        return "\n".join(
            parts
        ).strip()

    # --------------------------------------------------------
    # List
    # --------------------------------------------------------

    if isinstance(
        research_gaps,
        list
    ):

        formatted = []

        for index, gap in enumerate(
            research_gaps,
            start=1
        ):

            # ----------------------------------------------
            # String gap
            # ----------------------------------------------

            if isinstance(
                gap,
                str
            ):

                value = gap.strip()

                if value:

                    formatted.append(
                        f"GAP {index}\n{value}"
                    )

                continue

            # ----------------------------------------------
            # Dictionary gap
            # ----------------------------------------------

            if isinstance(
                gap,
                dict
            ):

                gap_id = (
                    gap.get(
                        "gap_id"
                    )
                    or gap.get(
                        "id"
                    )
                    or f"GAP_{index}"
                )

                description = (
                    gap.get(
                        "description"
                    )
                    or gap.get(
                        "research_gap"
                    )
                    or ""
                )

                evidence = (
                    gap.get(
                        "evidence"
                    )
                    or ""
                )

                opportunity = (
                    gap.get(
                        "research_opportunity"
                    )
                    or ""
                )

                category = (
                    gap.get(
                        "category"
                    )
                    or ""
                )

                section = [
                    str(
                        gap_id
                    )
                ]

                if description:

                    section.append(
                        f"Description: {description}"
                    )

                if evidence:

                    section.append(
                        f"Evidence: {evidence}"
                    )

                if opportunity:

                    section.append(
                        f"Research Opportunity: {opportunity}"
                    )

                if category:

                    section.append(
                        f"Category: {category}"
                    )

                formatted.append(
                    "\n".join(
                        section
                    )
                )

        return "\n\n".join(
            formatted
        ).strip()

    return str(
        research_gaps
    ).strip()


# ============================================================
# IDEA NORMALIZATION
# ============================================================

def normalize_idea(
    idea: Any,
    index: int
) -> Dict[str, Any]:
    """
    Normalize one LLM-generated project idea.

    No project content is invented here.

    If a field is missing, it remains empty and the idea
    can subsequently fail validation.
    """

    if not isinstance(
        idea,
        dict
    ):

        return {}

    def get_value(
        *keys
    ):

        for key in keys:

            value = idea.get(
                key
            )

            if value is None:

                continue

            if isinstance(
                value,
                str
            ):

                value = value.strip()

                if value:

                    return value

            elif value != "":

                return value

        return ""

    return {
        "idea_id":
            get_value(
                "idea_id",
                "id"
            )
            or f"IDEA_{index}",

        "title":
            get_value(
                "title",
                "project_title",
                "name"
            ),

        "problem_statement":
            get_value(
                "problem_statement",
                "problem",
                "research_problem"
            ),

        "research_gap":
            get_value(
                "research_gap",
                "gap",
                "gap_description"
            ),

        "gap_category":
            get_value(
                "gap_category",
                "category"
            ),

        "proposed_approach":
            get_value(
                "proposed_approach",
                "approach",
                "methodology"
            ),

        "recommended_technologies":
            get_value(
                "recommended_technologies",
                "technologies",
                "technology",
                "tech_stack"
            ),

        "relevance":
            get_value(
                "relevance",
                "relevance_to_gap"
            ),

        "difficulty":
            get_value(
                "difficulty",
                "complexity"
            ),

        "evaluation":
            get_value(
                "evaluation",
                "evaluation_method",
                "evaluation_strategy"
            ),

        "expected_outcome":
            get_value(
                "expected_outcome",
                "outcome",
                "expected_result"
            ),
    }


# ============================================================
# VALIDATE IDEA
# ============================================================

def is_valid_idea(
    idea: Dict[str, Any]
) -> bool:
    """
    Validate that Ollama actually generated the core
    project information.

    No missing field is automatically fabricated.
    """

    required_fields = [
        "title",
        "problem_statement",
        "research_gap",
        "proposed_approach",
    ]

    for field in required_fields:

        value = idea.get(
            field
        )

        if value is None:

            return False

        if not str(
            value
        ).strip():

            return False

    return True


# ============================================================
# EXTRACT IDEA LIST
# ============================================================

def extract_ideas(
    parsed: Any
) -> List[Any]:
    """
    Extract the project-idea list from Ollama JSON.
    """

    if isinstance(
        parsed,
        list
    ):

        return parsed

    if not isinstance(
        parsed,
        dict
    ):

        return []

    wrapper_keys = [
        "ideas",
        "project_ideas",
        "results",
        "projects",
    ]

    for key in wrapper_keys:

        value = parsed.get(
            key
        )

        if isinstance(
            value,
            list
        ):

            return value

    nested = parsed.get(
        "response"
    )

    if isinstance(
        nested,
        dict
    ):

        return extract_ideas(
            nested
        )

    if isinstance(
        nested,
        list
    ):

        return nested

    return []


